// Builds src/cart/known-carts.ts, the table of known cartridge images by CRC-32:
// their titles, the memory map of .bin images that don't use the usual one, and
// whether they need the Intellivoice or the ECS. The sources are pinned:
//  - jzIntv's name list, which its author placed in the public domain;
//  - MAME's intv.hsi (CC0-1.0), whose extrainfo gives the memory maps.
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAME_LIST =
  'https://raw.githubusercontent.com/lutris/jzintv/320f12c029bfe2750d657d19731af30daec5cd35/name/name_list.c';
const HSI = 'https://raw.githubusercontent.com/mamedev/mame/878a16dda136d6e234ded19527fe914da4488cb3/hash/intv.hsi';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'cart', 'known-carts.ts');

async function text(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

const carts = new Map();
const entry = (crc) => {
  if (!carts.has(crc)) carts.set(crc, {});
  return carts.get(crc);
};

for (const [, crc, year, ecs, voice, title] of (await text(NAME_LIST)).matchAll(
  /\{\s*0x([0-9A-F]{8}),\s*(\d+),(\d),(\d),\s*"((?:[^"\\]|\\.)*)"\s*\}/gi,
)) {
  Object.assign(entry(parseInt(crc, 16)), {
    title: title.replace(/\\"/g, '"'),
    year: Number(year),
    ...(ecs === '1' && { ecs: true }),
    ...(voice === '1' && { voice: true }),
  });
}

/** MAME packs each block as (address / $1000) << 4 | (words / $800); $4000 means $4800. */
const block = (packed) => {
  let start = (packed >> 4) * 0x1000;
  if (start === 0x4000) start = 0x4800;
  return [start, (packed & 0x0f) * 0x800];
};
const isUsualMap = (blocks) =>
  blocks.every(([start, words], i) => [0x5000, 0xd000, 0xf000][i] === start && words === [0x2000, 0x1000, 0x1000][i]);

for (const [, crc, name, body] of (await text(HSI)).matchAll(/<hash crc32="([0-9a-f]+)" name="([^"]+)">(.*?)<\/hash>/gs)) {
  const cart = entry(parseInt(crc, 16));
  if (!cart.title) {
    cart.title = name
      .replace(/&amp;/g, '&')
      .replace(/\s*\[[^\]]*\]/g, '')
      .replace(/\s*\((Mattel|Imagic|Activision|Intv Corp|Atarisoft|Coleco|Parker Bros|Sega|PD|Realtime|Nice Ideas|Interphase|Dextell|Data East|Mystic|Sears|INTV)\)$/i, '')
      .trim();
    const year = body.match(/<year>(\d+)<\/year>/);
    if (year) cart.year = Number(year[1]);
  }
  const extra = body.match(/<extrainfo>([^<]+)<\/extrainfo>/);
  if (!extra) continue;
  const [, ...rest] = extra[1].trim().split(/\s+/).map(Number);
  const blocks = rest.slice(0, 4).filter(Boolean).map(block);
  if (!isUsualMap(blocks)) cart.map = blocks;
  if (rest[4]) cart.ram = block(rest[4]);
  if (rest[5] & 1) cart.ecs = true;
  if (rest[5] & 2) cart.voice = true;
}

const lines = [...carts]
  .sort(([a], [b]) => a - b)
  .map(([crc, cart]) => `  [0x${crc.toString(16).padStart(8, '0')}, ${JSON.stringify(cart)}],`);
await writeFile(
  out,
  `// Generated by scripts/build-cart-database.mjs from jzIntv's public-domain name list and MAME's
// intv.hsi (CC0-1.0). Do not edit by hand.

export interface KnownCart {
  title: string;
  year?: number;
  /** Where a .bin image's blocks go, in file order: [address, words]. Absent for the usual map. */
  map?: [number, number][];
  /** 8-bit RAM on the cartridge: [address, bytes]. */
  ram?: [number, number];
  /** Needs the Entertainment Computer System. */
  ecs?: boolean;
  /** Talks through the Intellivoice. */
  voice?: boolean;
}

export const KNOWN_CARTS: ReadonlyMap<number, KnownCart> = new Map<number, KnownCart>([
${lines.join('\n')}
]);
`,
);
console.log(`Wrote ${carts.size} cartridges to src/cart/known-carts.ts`);
